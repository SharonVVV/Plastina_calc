"""
Корреляции свободной конвекции для ГОРИЗОНТАЛЬНЫХ нагретых поверхностей.

Используется в Задаче №2 для верхнего торца плиты.

Источник (отечественный):
    Леонтьев А.И. (ред.) «Теория тепломассообмена». — 1979.
    Глава 7. Теплообмен при естественной конвекции.

    Стр. 309, формула (7.30):
        «В том случае, когда нагретая (теплоотдающая) поверхность обращена
        вверх, используется формула  Nu = 0,54·Ra^(1/4),  справедливая для
        квадратных пластин при 10⁵ < Ra < 2·10⁷. В этих формулах физические
        свойства отнесены к температуре 0,5(T_ст + T_ж). В формуле (7.30) за
        характерный размер принята сторона квадрата.»

    Стр. 312, универсальная корреляция Nu = C·Ra^n:
        5·10²  < Ra < 2·10⁷ : C = 0,54,  n = 1/4 — «развитая ламинарная конв.»
        2·10⁷  < Ra < 10¹³ : C = 0,135, n = 1/3 — «переходный + турбулентный»

Расширение на прямоугольные плиты (не строго в источнике): за характерный
размер берётся L_c = A/P (т.н. характеристический размер Lloyd-Moran 1974).
Для квадрата стороны a: L_c = a²/(4a) = a/4, т.е. в 4 раза меньше, чем
«сторона квадрата» в Леонтьеве. Это стандартная конвенция для нестандартных
форм горизонтальных плит в отечественных и зарубежных монографиях
(Incropera, формула 9.30; Holman, формула 7-42).

Для нижней грани (поверхность обращена вниз) в Задаче №2 по ТЗ пользователя
конвекция не учитывается — только излучение. Поэтому соответствующая
функция в модуле не реализована.
"""

from __future__ import annotations

import math
from dataclasses import dataclass


@dataclass
class HorizNuResult:
    Nu: float
    regime: str         # 'lam' / 'turb' / 'out'
    Ra: float
    L_char_m: float     # характеристический размер L_c = A/P


# Границы режимов по Леонтьеву 1979, стр. 309 (фрагмент 10⁵…2·10⁷) и стр. 312
# (общая корреляция).  Для нашей задачи Ra на верхнем торце обычно < 10⁵,
# поэтому строгая нижняя граница 10⁵ из (7.30) сигнализируется out_of_range.
_RA_LAM_MIN = 1.0e5
_RA_LAM_MAX = 2.0e7
_RA_TURB_MAX = 1.0e13


def char_length(area_m2: float, perimeter_m: float) -> float:
    """L_c = A/P — характеристический размер Lloyd-Moran для плоской
    горизонтальной поверхности произвольной формы."""
    return area_m2 / perimeter_m if perimeter_m > 0 else 0.0


def nu_leontiev_horizontal_up(Ra: float) -> HorizNuResult:
    """Леонтьев 1979 — горячая горизонтальная поверхность лицом вверх.

        Nu = 0,54 · Ra^(1/4),   10⁵ ≤ Ra ≤ 2·10⁷    (формула 7.30, стр. 309)
        Nu = 0,135 · Ra^(1/3),  2·10⁷ ≤ Ra ≤ 10¹³   (универс. корр., стр. 312)
    """
    if Ra <= 0:
        return HorizNuResult(0.0, 'out', Ra, 0.0)
    if Ra < _RA_LAM_MIN:
        # Параметр ниже опубликованного диапазона. Возвращаем ламинарную
        # экстраполяцию с флагом out — физически конвекция всё равно
        # реализуется, но точность вне коридора источника.
        return HorizNuResult(0.54 * Ra ** 0.25, 'out', Ra, 0.0)
    if Ra <= _RA_LAM_MAX:
        return HorizNuResult(0.54 * Ra ** 0.25, 'lam', Ra, 0.0)
    if Ra <= _RA_TURB_MAX:
        return HorizNuResult(0.135 * Ra ** (1.0 / 3.0), 'turb', Ra, 0.0)
    return HorizNuResult(0.135 * Ra ** (1.0 / 3.0), 'out', Ra, 0.0)


def alpha_horizontal_up(
    t_s_C: float, t_fluid_C: float, P_Pa: float,
    area_m2: float, perimeter_m: float,
) -> tuple[float, HorizNuResult]:
    """Коэф. теплоотдачи (Вт/(м²·К)) для горячей грани лицом вверх по Леонтьеву 1979.

    Свойства воздуха — при плёночной температуре T_f = 0.5·(T_s + T_∞).
    Характеристический размер — L_c = A/P (см. шапку модуля).

    Возвращает (α, NuResult).
    """
    from properties import get_air_properties

    if area_m2 <= 0 or perimeter_m <= 0:
        return 0.0, HorizNuResult(0.0, 'out', 0.0, 0.0)
    if t_s_C <= t_fluid_C:
        return 0.0, HorizNuResult(0.0, 'out', 0.0, 0.0)

    L_c = char_length(area_m2, perimeter_m)
    t_film = 0.5 * (t_s_C + t_fluid_C)
    air = get_air_properties(t_film, P_Pa)
    beta = 1.0 / (t_film + 273.15)
    g = 9.80665

    Ra = g * beta * (t_s_C - t_fluid_C) * L_c ** 3 / (air.nu ** 2) * air.Pr
    res = nu_leontiev_horizontal_up(Ra)
    res.L_char_m = L_c
    alpha = res.Nu * air.lam / L_c if L_c > 0 else 0.0
    return alpha, res
